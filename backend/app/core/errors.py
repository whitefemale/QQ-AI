def not_found(entity: str) -> AppError:
    return AppError(ErrorCode.NOT_FOUND, f"{entity}不存在或已被删除。", status_code=404)


def planned(feature: str) -> AppError:
    return AppError(
        ErrorCode.OPERATION_PLANNED,
        f"{feature}尚未实现，当前版本仅预留接口。",
        status_code=501,
    )
